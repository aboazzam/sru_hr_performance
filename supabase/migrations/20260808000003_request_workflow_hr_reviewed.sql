-- ============================================================================
-- تبسيط دورة طلب الاحتياج إلى أربع حالات واضحة
--
-- بلاغ مباشر: "المفروض حالتين عند المنسق: مسودة في حالة لم ينتهِ بعد، ثم في
-- حالة التقديم تتغير إلى مراجعة الموارد البشرية. وعند الضغط عليها ممن له
-- صلاحية تظهر عنده تمت المراجعة وتظهر عند الأدمن للاعتماد أو الرفض أو
-- التعديل. وبعد الاعتماد تظهر معتمدة وتُدرج تلقائيًا في الخطة."
--
-- الدورة السابقة كانت ست خطوات يمرّ الطلب فيها بحالتَي "مرفوع" و"مُدرج في
-- الخطة" لا تعنيان شيئًا لمن يقرأهما: المنسّق يرفع فيبقى عنده "مسودة" في
-- حين يرى الأدمن "رفع الطلب"، ثم يضغط فتظهر "مراجعة الموارد البشرية" ثم
-- "إدراج في الخطة" — أي أن الأدمن كان يؤدي خطوات الموارد البشرية بنفسه.
--
-- الدورة الجديدة:
--   مسودة  --(المنسّق يرفع)-->  مراجعة الموارد البشرية
--          --(الموارد البشرية تراجع)-->  تمت المراجعة
--          --(الأدمن يعتمد)-->  معتمد  + إدراج تلقائي في الخطة
-- مع الرفض والإعادة للتعديل متاحَين في المرحلتين.
--
-- ---------------------------------------------------------------------------
-- ماذا يحدث للحالتين القديمتين
-- ---------------------------------------------------------------------------
-- `submitted` و`included_in_plan` تبقيان في قيد CHECK ولا يُنتجهما شيء بعد
-- اليوم. لم تُحذفا من القيد عمدًا: حذف قيمة من قيد قائم يفشل إن وُجد صف
-- واحد يحملها، وحالة القاعدة قد تتغير بين كتابة هذه الهجرة وتشغيلها على
-- بيئة أخرى -- فالإبقاء عليهما أرخص من كسر الترحيل.
--
-- والصفوف القائمة تُرحَّل: `submitted` تعني حرفيًا ما تعنيه
-- `under_hr_review` في النموذج الجديد (طلب رُفع وينتظر الموارد البشرية)،
-- و`included_in_plan` تعني ما تعنيه `hr_reviewed` (رُوجع وينتظر الاعتماد).
-- عدد الصفوف المتأثرة اليوم صفر في الإنتاج (فُحص قبل الكتابة)، لكن الترحيل
-- مكتوب لأن الهجرة ستعمل على بيئات أخرى لا أعرف حالتها.
-- ============================================================================

BEGIN;

ALTER TABLE recruitment_requests DROP CONSTRAINT recruitment_requests_status_check;

ALTER TABLE recruitment_requests
  ADD CONSTRAINT recruitment_requests_status_check
    CHECK (status = ANY (ARRAY[
      'draft',
      'under_hr_review',
      'hr_reviewed',
      'returned_for_revision',
      'approved',
      'rejected',
      -- مهجورتان: لا يُنتجهما شيء، وتُقبلان لئلا يفشل القيد على صف قديم.
      'submitted',
      'included_in_plan'
    ]));

UPDATE recruitment_requests SET status = 'under_hr_review' WHERE status = 'submitted';
UPDATE recruitment_requests SET status = 'hr_reviewed' WHERE status = 'included_in_plan';

COMMIT;

