--    CHECK to cover them (only when non-NULL).
--
-- [استنتاج] decisions made without an explicit source value, each isolated
-- and flagged inline: (a) one exact duplicate title name at two grades
-- under the same family ("مقدم خدمة" under المرافق at both grade 2 and
-- grade 4) -- kept the grade-2 occurrence (fits contextually alongside
-- other general-service roles there), dropped the grade-4 one, since
-- job_titles has a UNIQUE(job_family_id, name_ar) constraint;
-- (b) academic titles have no explicit 1-14/16 grade_level in the source
-- at all -- ranked all 9 by their real midpoint salary (descending) and
-- assigned grade_level 9 down to 1 accordingly, a data-driven ranking
-- rather than a guess; (c) admin titles with no specific job-family
-- column filled (the per-level "generic" title, e.g. CXO at grade 16)
-- are assigned to a new placeholder family "عام" (General), since
-- job_titles.job_family_id is NOT NULL and these titles are real and
-- distinct from the family-specific ones at the same level, not
-- something to silently drop; (d) effective_date for every salary_scale
-- row is set to CURRENT_DATE (today), since the source doesn't state one.
-- ============================================================================

