-- ============================================================================
-- الجنس المطلوب في طلب الاحتياج
--
-- بطلب مباشر: "أضف الجنس ذكر أو أنثى".
--
-- القيم `Male`/`Female` بحروفها الكبيرة عمدًا — وهي المفردات نفسها
-- المستعملة في `profiles.gender` منذ استيراد بيانات الموظفين (2026-07-24)
-- وفي نموذج إضافة موظف. اختراع مفردات جديدة ('male'/'ذكر'/…) كان سيعني
-- قاموسين لنفس المعنى في مخطط واحد، وأول تقرير يجمع بين الجدولين يكشف
-- الفرق.
--
-- NULLABLE عمدًا: كثير من الطلبات لا تشترط جنسًا، وإجبار الحقل كان سيدفع
-- مقدّم الطلب إلى اختيار قيمة لا يقصدها. غيابه يعني "غير مشترط" لا "غير
-- معروف".
--
-- CHECK لا ENUM: يطابق ما فعله `profiles.gender` (TEXT حر) مع إضافة قيد
-- يمنع القيم العشوائية — وهو أقرب ما يمكن دون تغيير عمود قائم في جدول آخر.
-- ============================================================================

BEGIN;

ALTER TABLE recruitment_requests
  ADD COLUMN gender TEXT
    CHECK (gender IS NULL OR gender = ANY (ARRAY['Male', 'Female']));

COMMENT ON COLUMN recruitment_requests.gender IS
  'الجنس المطلوب للوظيفة: Male | Female، وNULL تعني غير مشترط. نفس مفردات profiles.gender.';

COMMIT;

