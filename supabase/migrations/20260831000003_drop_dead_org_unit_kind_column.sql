-- =========================================================================
-- حذف العمود المعطَّل `org_units.kind` ونوعه (2026-08-31، بطلب مالك
-- المشروع بعد استقرار النسخة الجديدة على الإنتاج).
--
-- العمود صار بلا قارئ منذ 20260830000002، حين انتقل الشكل التنظيمي من
-- ENUM ثابت إلى جدول `org_unit_kinds` يملكه المستخدم، وأشار إليه
-- `org_units.kind_id`. تُرك حينها معطَّلًا لا محذوفًا عمدًا: حذف عمود
-- بينما الكود المنشور ما زال يقرؤه هو ما أوقع `/org-units` في «لا توجد
-- وحدات تنظيمية» في اليوم نفسه — خطأ تسلسل، لا خطأ مخطط.
--
-- الشرطان اللذان كان الحذف ينتظرهما تحققا وفُحصا قبل كتابة هذه الهجرة:
--   • لا استعلام في `src/` يقرأ العمود أو يكتبه (فُحص على main بعد
--     دمج #327، لا على نسخة قديمة).
--   • لا سياسة RLS ولا فهرس ولا view يعتمد عليه، والمستعمل الوحيد للنوع
--     `org_unit_kind` هو هذا العمود نفسه.
--
-- ولأن القيم القديمة تُفقد بالحذف، تحفظها هذه الهجرة أولًا في
-- `org_units_kind_backup` — جدول أرشيفي بلا RLS ولا قارئ، غرضه الوحيد أن
-- يبقى الرجوع ممكنًا لو تبيّن أن أحدًا كان يحتاجها. احذفه متى اطمأننت.
-- =========================================================================

BEGIN;

CREATE TABLE org_units_kind_backup AS
SELECT id, name_ar, kind::text AS old_kind FROM org_units WHERE kind IS NOT NULL;

-- تحقق قبل الحذف: كل وحدة حية لها شكل تنظيمي في النظام الجديد، وإلا
-- فالحذف يفقد معلومة لا نسخة زائدة.
DO $guard$
DECLARE missing integer;
BEGIN
  SELECT count(*) INTO missing FROM org_units WHERE deleted_at IS NULL AND kind_id IS NULL;
  IF missing > 0 THEN
    RAISE EXCEPTION 'بقيت % وحدة بلا kind_id — لا يجوز حذف العمود القديم', missing;
  END IF;
END $guard$;

ALTER TABLE org_units DROP COLUMN kind;
DROP TYPE org_unit_kind;

COMMENT ON TABLE org_units_kind_backup IS
  'نسخة من عمود org_units.kind المحذوف (2026-08-31) — أرشيف للرجوع فقط، لا يقرؤه التطبيق.';

COMMIT;
