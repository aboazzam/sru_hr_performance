-- تصنيف حقيقي للوحدات التنظيمية (2026-08-30، بطلب مالك المشروع بعد سؤاله
-- عن مصدر عمود "التصنيف" الظاهر على الشاشة).
--
-- العمود القديم `type` لم يكن تصنيفًا إداريًا أصلًا: هجرة 20260716000003
-- تقول في ترويستها إنه مأخوذ عن **لون الصندوق** في صورة الهيكل التنظيمي
-- (حوكمة/دعم/أكاديمي/إداري/تطوير أعمال)، وإنه ليس تصنيف وحدات موثّقًا،
-- وإن وُجد تصنيف حقيقي لاحقًا «فالأولى أن يأخذ عمودًا خاصًّا به». هذا هو
-- ذلك العمود، والقديم يزول معه لأن لا قارئ له في التطبيق كلّه سوى شاشة
-- الوحدات نفسها (مفحوص: العمود الوحيد المستعمل للنوع القديم، ولا دالة
-- تقرؤه).
--
-- التصنيف ليس اختراعًا: هو مستخرج من أسماء الوحدات نفسها، وكل قيمة موجودة
-- لأن الاسم يصرّح بها — إدارة، مكتب، مركز، كلية، مجلس، لجنة، أمانة، وحدة.
-- التوزيع الناتج: إدارة 23، مكتب 11، مركز 5، كلية 4، مجلس 4، أمانة 2،
-- وحدة 1، لجنة 1.
--
-- **[استنتاج] القيمة التاسعة `leadership`**: سبع وحدات لا يصرّح اسمها بأي
-- شكل تنظيمي لأنها مناصب قيادية مرسومة كصناديق في المخطط — رئيس الجامعة،
-- نائب الرئيس للشؤون الأكاديمية، النواب المساعدون الثلاثة، المشرفة على
-- القسم النسائي، عمداء الكليات. تسميتها «قيادة» قرار لا نصّ، وهي الحالة
-- الوحيدة التي لم يُملِها الاسم. وإن كان الأصوب توزيعها على أشكال أخرى
-- فذلك تعديل صف واحد من الشاشة نفسها الآن، لا هجرة.
--
-- ولا قيمة افتراضية للعمود عمدًا: إضافة وحدة تُلزم باختيار شكلها بدل أن
-- يُزرع لها شكل صامت.
-- =========================================================================

BEGIN;

CREATE TYPE org_unit_kind AS ENUM (
  'council',
  'committee',
  'secretariat',
  'leadership',
  'college',
  'department',
  'office',
  'center',
  'unit'
);

ALTER TABLE org_units ADD COLUMN kind org_unit_kind;

UPDATE org_units SET kind = CASE
  WHEN name_ar LIKE 'كلية %' THEN 'college'
  WHEN name_ar LIKE 'مجلس %' OR name_ar LIKE 'المجلس %' THEN 'council'
  WHEN name_ar LIKE 'لجنة %' OR name_ar LIKE 'اللجنة %' THEN 'committee'
  WHEN name_ar LIKE 'أمانة %' THEN 'secretariat'
  WHEN name_ar LIKE 'إدارة %' OR name_ar LIKE 'الإدارة %' THEN 'department'
  WHEN name_ar LIKE 'مركز %' THEN 'center'
  WHEN name_ar LIKE 'مكتب %' THEN 'office'
  WHEN name_ar LIKE 'وحدة %' THEN 'unit'
  ELSE 'leadership'
END::org_unit_kind;

ALTER TABLE org_units ALTER COLUMN kind SET NOT NULL;

ALTER TABLE org_units DROP COLUMN type;
DROP TYPE org_unit_category;

COMMENT ON COLUMN org_units.kind IS
  'الشكل التنظيمي للوحدة (مجلس/لجنة/أمانة/قيادة/كلية/إدارة/مكتب/مركز/وحدة) — مستخرج من أسماء الوحدات، بخلاف العمود السابق الذي كان لون صندوق المخطط.';

COMMIT;
