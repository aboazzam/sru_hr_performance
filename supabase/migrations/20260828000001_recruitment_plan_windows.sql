-- ---------------------------------------------------------------------------
-- خطة التوظيف مزمَّنة: نافذة استقبال الطلبات، وفترة الخطة
-- 2026-08-28
-- ---------------------------------------------------------------------------
-- بطلب مباشر: «اريد خطة التوظيف تكون مزمنة بزمن مثل دورة التقييم بحيث يكون
-- لها زمنين: الزمن الأول السماح للادارات باضافة الطلبات، والزمن الثاني يشير
-- الى زمن الخطة، بحيث اذا كان الطلب وقت الزمن وتمت الموافقة عليه يدرج في
-- الخطة، اما اذا كان الاحتياج بعد اقرار الخطة فيكون طلب احتياج خارج الخطة».
--
-- ما تضيفه هذه الهجرة:
--   1) أربعة تواريخ على `recruitment_plans` — نافذة الاستقبال وفترة الخطة.
--   2) عمود `out_of_plan` على `recruitment_requests` يسجّل أن الطلب رُفع
--      خارج نافذة الاستقبال.
--
-- ### التواريخ اختيارية (NULL)، وهذا مقصود
-- خطة 2027 الحقيقية موجودة اليوم بلا أي تواريخ. جعل الأعمدة NOT NULL كان
-- سيوجب اختلاق تواريخ لها، وهو ما يمنعه انضباط هذا المشروع في البيانات.
-- فالأعمدة اختيارية، و«لا نافذة مضبوطة» تعني **الاستقبال مفتوح** — أي
-- السلوك القائم اليوم حرفيًا، فلا ينكسر شيء بمجرد تطبيق الهجرة.
-- [استنتاج]: قراءة «غير مضبوط = مفتوح» لم تُطلب نصًّا، لكن نقيضها كان
-- سيوقف رفع الطلبات فورًا على كل خطة قائمة، وهو ضرر لم يطلبه أحد.
--
-- ### `date` لا `timestamptz`
-- مثل `evaluation_cycles.start_date/end_date` تمامًا: النافذة تُقاس باليوم لا
-- بالساعة، والمقارنة تجري نصًّا على YYYY-MM-DD في اليوم بتوقيت العرض —
-- وهو ما يتفادى خطأ اليوم الواحد الذي وقع فيه هذا المشروع فعلًا مرة (استيراد
-- الهيكل التنظيمي) حين حوّل تاريخًا عبر `new Date(iso)`.
--
-- ### `out_of_plan` مخزَّن لا مشتق — خلافًا لحالة دورة التقييم
-- حالة الدورة تُشتق من تاريخيها لأنها وصفٌ للحاضر. أما «رُفع خارج النافذة»
-- فوصفٌ للحظة الرفع، وهي حقيقة لا تتغيّر. ولو اشتُقّت لتغيّرت مع الزمن:
-- طلبٌ رُفع في مارس 2026 يقع خارج نافذة خطة 2026، لكنه يقع داخل نافذة خطة
-- 2027 إن فُتحت لاحقًا لتشمل ذلك التاريخ — فيصير الطلب نفسه «داخل الخطة»
-- بعد أن كان خارجها، دون أن يفعل أحد شيئًا. ولأن تحرير تواريخ خطة يجب ألّا
-- يعيد تصنيف طلبات فُصل فيها أصلًا، يُحسب التصنيف مرة واحدة في الخادم ويُخزَّن.
--
-- NULL في `out_of_plan` تعني «لم يُصنَّف بعد»، وهي حال المسودة: الطلب الذي لم
-- يُرفع لم يصل أحدًا بعد، فلا معنى لقياسه على نافذة. القيمة تُكتب لحظة أول
-- وصول للموارد البشرية (الرفع)، لا لحظة إنشاء المسودة.
-- [استنتاج]: «وقت الزمن» في الطلب لم تحدّد أهي لحظة الإنشاء أم الرفع؛ اختير
-- الرفع لأن المسودة ليست طلبًا لأحد بعد.
--
-- ### الطلب خارج الخطة لا يُمنع
-- يُوسَم فقط. النص صريح: «فيكون طلب احتياج خارج الخطة» — أي أنه طلبٌ قائم
-- له صفة، لا طلبٌ مرفوض. ودمجه في خطة لاحقًا يبقى ممكنًا كما هو، والوسم
-- يبقى معه لأنه يسجّل كيف نشأ، وهو الحقيقة القابلة للتدقيق.
--
-- ### RLS
-- لا سياسة جديدة: الأعمدة تنضم لجدولين لهما سياساتهما، و RLS يرشّح الصفوف لا
-- الأعمدة. من يعدّل الخطة اليوم (`recruitmentPlan` ≥ prepare) هو من يضبط
-- نافذتها، ومن يقرأ الطلب يقرأ وسمه.
-- ---------------------------------------------------------------------------

BEGIN;

ALTER TABLE recruitment_plans
  ADD COLUMN requests_open_at DATE,
  ADD COLUMN requests_close_at DATE,
  ADD COLUMN plan_start_date DATE,
  ADD COLUMN plan_end_date DATE;

-- كل قيد يقبل NULL على أي طرف: نافذة نصف مضبوطة (فُتحت ولم يُحدَّد إغلاقها)
-- حالٌ مشروعة أثناء الإعداد، والقيد يمنع الانعكاس فقط لا النقص.
ALTER TABLE recruitment_plans
  ADD CONSTRAINT recruitment_plans_intake_window_valid
    CHECK (
      requests_open_at IS NULL
      OR requests_close_at IS NULL
      OR requests_close_at >= requests_open_at
    ),
  ADD CONSTRAINT recruitment_plans_period_valid
    CHECK (
      plan_start_date IS NULL
      OR plan_end_date IS NULL
      OR plan_end_date >= plan_start_date
    );

COMMENT ON COLUMN recruitment_plans.requests_open_at IS
  'بداية نافذة استقبال طلبات الاحتياج من الإدارات. NULL = الاستقبال مفتوح بلا بداية محدّدة.';
COMMENT ON COLUMN recruitment_plans.requests_close_at IS
  'آخر يوم تُقبل فيه الطلبات ضمن الخطة (شامل). NULL = بلا موعد إغلاق.';
COMMENT ON COLUMN recruitment_plans.plan_start_date IS
  'بداية فترة الخطة نفسها — الزمن الذي تُنفَّذ فيه.';
COMMENT ON COLUMN recruitment_plans.plan_end_date IS
  'نهاية فترة الخطة (شامل).';

ALTER TABLE recruitment_requests
  ADD COLUMN out_of_plan BOOLEAN;

COMMENT ON COLUMN recruitment_requests.out_of_plan IS
  'طلب احتياج خارج الخطة: رُفع بعد إغلاق نافذة الاستقبال أو بعد إقرار الخطة. NULL = مسودة لم تُرفع بعد فلم تُصنَّف.';

-- الطلبات القائمة تبقى NULL: تصنيفها الآن يقتضي معرفة نافذةٍ لم تكن موجودة
-- لحظة رفعها، فأي قيمة نضعها اختلاق. تظهر في الواجهة بلا وسم، وهو الصدق.

COMMIT;
