BEGIN;

CREATE TYPE competency_type AS ENUM ('core', 'specialized');
CREATE TYPE behavioral_level AS ENUM ('basic', 'practitioner', 'advanced', 'professional');

-- ----------------------------------------------------------------------------
-- competency_pillars / competency_domains — the 3x3 structure (دعم/أكاديمي/
-- ابتكار pillars, 3 domains each). name_en left nullable: no English
-- translation of these Arabic domain-source names exists yet (see
-- competencies.ts's header comment — don't fabricate one here either).
-- ----------------------------------------------------------------------------

CREATE TABLE competency_pillars (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name_ar TEXT NOT NULL UNIQUE,
  name_en TEXT
);

CREATE TABLE competency_domains (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  pillar_id UUID NOT NULL REFERENCES competency_pillars (id) ON DELETE CASCADE,
  name_ar TEXT NOT NULL,
  name_en TEXT,
  UNIQUE (pillar_id, name_ar)
);

-- ----------------------------------------------------------------------------
-- competencies — job_family_id has no FK yet: no job_families table exists
-- in this repo's migrations (same situation as user_roles.org_unit_id in
-- the roles migration). Add the FK in the migration that introduces
-- job_families.
-- ----------------------------------------------------------------------------

CREATE TABLE competencies (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  domain_id UUID NOT NULL REFERENCES competency_domains (id) ON DELETE CASCADE,
  name_ar TEXT NOT NULL,
  type competency_type NOT NULL,
  definition_ar TEXT NOT NULL,
  expected_impact_ar TEXT NOT NULL,
  job_family_id UUID, -- no FK yet: job_families table doesn't exist in this repo's migrations.
  deleted_at TIMESTAMPTZ,
  UNIQUE (domain_id, name_ar)
);

COMMENT ON COLUMN competencies.job_family_id IS 'NULL in every seeded row today (job_families does not exist yet, so there is nothing to reference). Intended meaning once populated: NULL = applies to all job families; only "specialized" competencies are expected to eventually get a specific job_family_id, "core" ones should stay NULL by design.';

-- ----------------------------------------------------------------------------
-- competency_levels — one row per (competency, behavioral_level), always
-- exactly 4 per competency in the current data. behavior_ar contains
-- multiple '\n'-joined indicator lines (see header note).
-- ----------------------------------------------------------------------------

CREATE TABLE competency_levels (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  competency_id UUID NOT NULL REFERENCES competencies (id) ON DELETE CASCADE,
  level behavioral_level NOT NULL,
  behavior_ar TEXT NOT NULL,
  behavior_en TEXT,
  UNIQUE (competency_id, level)
);

