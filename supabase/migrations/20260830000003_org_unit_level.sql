-- =========================================================================
-- مستوى الوحدة التنظيمية (2026-08-30، بطلب مالك المشروع: «اضافة المستوى»،
-- وباختياره الصريح بين قراءتين: مستوى **للوحدة نفسها** مرتبط بمستويات
-- الهيكل القائمة، لا مستوى لكل منصب — «الأولى»).
--
-- يشير إلى `org_structure_levels` نفسه الذي تستعمله مناصب الهيكل، لا إلى
-- جدول مستويات ثانٍ ولا إلى رقم حر: مستوى الوحدة ومستوى منصبها في الرسم
-- يجب أن يتكلما اللغة نفسها، ومصدران للمستوى ينحرفان كما انحرف من قبل
-- نسخة الوحدات المكتوبة في الكود عن جدول `org_units`.
--
-- **قابل لـNULL، وفارغ في كل الوحدات الثامنة والخمسين عمدًا**: لا مصدر
-- يقول أي وحدة عند أي مستوى. المستويات القائمة اليوم مرتبة رتبيًّا لا
-- بعمق الشجرة (١، C2، C3، «الإدارات المرتبطة بالرئيس مباشرة»، «نائب
-- الرئيس»، C4، C5، C6)، فاشتقاقه من `parent_id` سيكون تخمينًا لا نقلًا.
-- يملؤه المستخدم من الشاشة، كما فعل `type_id` في الهجرة السابقة.
--
-- ON DELETE SET NULL لا RESTRICT: حذف مستوى من شاشة الهيكل شأن تلك
-- الشاشة، ولا ينبغي أن يمنعه ارتباط وحدة به — تفقد الوحدة مستواها ويبقى
-- كل شيء آخر سليمًا.
-- =========================================================================

BEGIN;

ALTER TABLE org_units
  ADD COLUMN level_id uuid REFERENCES org_structure_levels(id) ON DELETE SET NULL;

CREATE INDEX org_units_level_id_idx ON org_units (level_id);

COMMENT ON COLUMN org_units.level_id IS
  'مستوى الوحدة ضمن مستويات الهيكل التنظيمي نفسها (org_structure_levels) — اختياري، ويملؤه المستخدم إذ لا مصدر يشتق منه.';

COMMIT;
