-- ============================================================================
-- إتاحة `job_title_competencies` لدور التوظيف
--
-- نموذج طلب الاحتياج صار يعبّئ الجدارات تلقائيًا من جدارات المسمى الوظيفي
-- المختار. لكن `job_title_competencies_select` تتطلب `careerPath >= view`،
-- وهو مجال لا يحمله دور "منسق شؤون الموظفين" إطلاقًا.
--
-- لوحظ أثناء الفحص: حساب يحمل دور المنسق **وحده** لم تُحدَّد له أي جدارة،
-- بينما نجحت التعبئة لموظف حقيقي يحمل المنسق **مع** دور "موظف" — لأن
-- "موظف" يحمل `careerPath=view` فيرى الجدول بالمصادفة.
--
-- وهذا بالضبط نوع الهشاشة الموثّق سابقًا في هذا المشروع: ميزة تعمل لأن
-- مصفوفة الصلاحيات اليوم تصادف أن تسمح بها، لا لأن التصميم يضمنها. فأي
-- منسّق يُنشأ لاحقًا بلا دور "موظف" كانت الميزة ستصمت له بلا رسالة.
--
-- العلاج بنفس شكل 20260807000003 (org_units/job_titles/competencies):
-- إضافة فرع للتوظيف عند مستوى `view`، مع الإبقاء على الفرع القائم حرفيًا
-- فلا يفقد أي دور رؤيةً يملكها اليوم.
--
-- الجدول مرجعي بحت (أي مسمى يتطلب أي جدارة)، بلا بيانات شخصية ولا أرقام
-- رواتب — فإتاحته لمن يعدّ طلب احتياج لا تكشف شيئًا حساسًا، بخلاف
-- `salary_scale` التي قُصرت عمدًا على مستوى `recommend`.
-- ============================================================================

BEGIN;

DROP POLICY job_title_competencies_select ON job_title_competencies;
CREATE POLICY job_title_competencies_select ON job_title_competencies
  FOR SELECT TO authenticated
  USING (
    check_vpra_global('careerPath'::process_area, 'view'::vpra_level)
    OR check_vpra_global('recruitmentPlan'::process_area, 'view'::vpra_level)
    OR check_vpra_global('recruitmentBudget'::process_area, 'view'::vpra_level)
  );

COMMIT;

