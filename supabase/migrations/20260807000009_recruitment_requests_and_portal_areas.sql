-- ============================================================================
-- مجالا صلاحية جديدان تحت قسم "التوظيف":
--   recruitmentRequests -- طلب الاحتياج
--   recruitmentPortal   -- بوابة التوظيف (الداخلية والخارجية)
--
-- بطلب مباشر: "في الصلاحيات وتحت سيكشن التوظيف أضف صلاحية طلب الاحتياج
-- وبوابة التوظيف" — أي أن يصبحا صفَّين قابلَين للمنح في مصفوفة /admin بدل
-- أن يكونا مطويَّين داخل مجالات أخرى.
--
-- قبل هذا: طلبات الاحتياج كانت مربوطة بـ`recruitmentPlan`، والبوابة
-- بـ`vacancies`. فصلهما يتيح -- مثلًا -- منسّقًا يرفع الطلبات دون أن يرى
-- الخطة، أو موظفًا يتصفّح البوابة دون صلاحية على الشواغر.
--
-- خطوة مستقلة عن استعمالهما (ALTER TYPE ... ADD VALUE لا يمكن استخدام
-- قيمته في المعاملة نفسها) -- نفس النمط المتبع في كل مجال أُضيف سابقًا.
-- الهجرة التالية 20260807000010 هي التي تستعملهما.
-- ============================================================================

ALTER TYPE process_area ADD VALUE IF NOT EXISTS 'recruitmentRequests';
ALTER TYPE process_area ADD VALUE IF NOT EXISTS 'recruitmentPortal';

